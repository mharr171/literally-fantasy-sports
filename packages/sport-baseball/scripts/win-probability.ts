// Usage: pnpm --filter @lfs/sport-baseball win-probability [games]
// Rebuilds src/win-probability-table.ts from harness games. Run it after
// tuning changes and commit the table with them.
import { writeFileSync } from "node:fs";
import { buildWinTable } from "../src/win-probability";

const games = Number(process.argv[2] ?? 20000);
const table = buildWinTable(games);
const body = Object.entries(table)
  .map(([k, v]) => `  "${k}": ${v},`)
  .join("\n");
writeFileSync(
  new URL("../src/win-probability-table.ts", import.meta.url),
  `// Generated by scripts/win-probability.ts from ${games} harness games: do not edit.\nimport type { WinTable } from "./win-probability";\n\nexport const WIN_TABLE: WinTable = {\n${body}\n};\n`,
);
console.log(`${Object.keys(table).length} situations from ${games} games`);
